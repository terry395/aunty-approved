// Builds netlify/functions/aunty-coach/knowledge.mjs from the Python bot's
// system_prompt.txt and knowledge/*.md, so the website and the Python bot
// always use the same personality and facts.
//
// Run after you edit anything in aunty-coach/:   npm run build:knowledge
// Check it is up to date (used by the tests):    npm run check:knowledge

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const botDir = path.join(root, "aunty-coach");
const outFile = path.join(root, "netlify", "functions", "aunty-coach", "knowledge.mjs");

// Same steps as load_system_prompt() in aunty-coach/aunty_coach.py
export function buildSystemPrompt() {
  const prompt = readFileSync(path.join(botDir, "system_prompt.txt"), "utf8");
  const kbDir = path.join(botDir, "knowledge");
  const parts = readdirSync(kbDir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => "### " + f.replace(/\.md$/, "") + "\n" + readFileSync(path.join(kbDir, f), "utf8"));
  return prompt + "\n\n=== KNOWLEDGE BASE (your only source of facts) ===\n\n" + parts.join("\n\n");
}

export function renderModule() {
  return (
    "// AUTO-GENERATED by scripts/build-aunty-knowledge.mjs. Do not edit by hand.\n" +
    "// Edit aunty-coach/system_prompt.txt or aunty-coach/knowledge/*.md, then run: npm run build:knowledge\n" +
    "export const SYSTEM_PROMPT = " + JSON.stringify(buildSystemPrompt()) + ";\n"
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const wanted = renderModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(outFile, "utf8"); } catch { /* missing */ }
    if (current !== wanted) {
      console.error("knowledge.mjs is out of date. Run: npm run build:knowledge");
      process.exit(1);
    }
    console.log("knowledge.mjs is up to date.");
  } else {
    writeFileSync(outFile, wanted);
    console.log("Wrote " + path.relative(root, outFile));
  }
}
